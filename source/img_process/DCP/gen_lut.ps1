# Run: powershell -ExecutionPolicy Bypass -File .\gen_lut.ps1 -Omega 0.75
# Smaller Omega gives gentler dehazing. Only the LUT file is overwritten.
param([ValidateRange(0.0,0.99999)][double]$Omega = 0.75)
$scale = [int][math]::Floor($Omega * 65536)
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('`timescale 1ns/1ps')
$lines.Add('`default_nettype none')
$lines.Add("// Generated by gen_lut.ps1: Omega=$Omega; scale=$scale")
$lines.Add('module dcp_air_lut(input wire [7:0] address, output reg [15:0] value);')
$lines.Add('always @* begin case (address)')
for ($a=0; $a -lt 256; $a++) {
    $value = [int][math]::Floor($scale / [math]::Max(1,$a))
    $lines.Add("8'd${a}: value = 16'd${value};")
}
$lines.Add("default: value = 16'd${scale};")
$lines.Add('endcase end endmodule')
$lines.Add('module dcp_t_lut(input wire [8:0] address, output reg [12:0] value);')
$lines.Add('always @* begin case (address)')
for ($t=16; $t -le 256; $t++) {
    $value = [int][math]::Floor(65536 / $t)
    $lines.Add("9'd${t}: value = 13'd${value};")
}
$lines.Add("default: value = 13'd4096;")
$lines.Add('endcase end endmodule')
$lines.Add('`default_nettype wire')
[IO.File]::WriteAllLines((Join-Path $PSScriptRoot 'dcp_recip_lut.v'), $lines, [Text.Encoding]::ASCII)
Write-Output "Generated dcp_recip_lut.v: Omega=$Omega, scale=$scale"
